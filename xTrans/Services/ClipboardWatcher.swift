import AppKit

/// Ghi clipboard và nhớ lần ghi đó là của xTrans, để bộ theo dõi không tự dịch lại (tránh vòng lặp).
@MainActor
enum Clipboard {
    private(set) static var lastOwnChangeCount = -1

    static func write(_ text: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
        lastOwnChangeCount = pb.changeCount
    }
}

/// Theo dõi clipboard: khi bạn copy chữ trong app được chọn (mặc định WeChat), tự gửi đi dịch.
///
/// macOS không báo sự kiện "vừa copy", nên mỗi 0,3 giây kiểm tra `changeCount` (chỉ là 1 con số,
/// gần như không tốn CPU). Chỉ khi số này đổi mới đọc nội dung và cho qua các lớp lọc.
@MainActor
final class ClipboardWatcher {
    static let shared = ClipboardWatcher()

    private var store: ChatStore?
    private var settings: SettingsStore?
    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var lastText = ""
    private var lastTextDate = Date.distantPast

    /// Các kiểu dữ liệu mà trình quản lý mật khẩu dùng để đánh dấu nội dung bí mật (chuẩn nspasteboard.org).
    private static let concealedTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    func configure(store: ChatStore, settings: SettingsStore) {
        self.store = store
        self.settings = settings
    }

    func start() {
        guard timer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount // không xử lý những gì đã copy trước khi mở app
        let timer = Timer(timeInterval: 0.3, repeats: true) { _ in
            Task { @MainActor in ClipboardWatcher.shared.tick() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func tick() {
        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count

        guard let settings, let store, settings.clipboardWatchEnabled else { return }

        // 1. Do chính xTrans ghi (vd tự chép bản dịch) → bỏ qua
        guard count != Clipboard.lastOwnChangeCount else { return }

        // 2. Chỉ nhận khi đang dùng app nằm trong danh sách (vd WeChat)
        guard let bundleID = NSWorkspace.shared.frontmostApplication?.bundleIdentifier,
              settings.clipboardWatchApps.contains(bundleID) else { return }

        // 3. Không bao giờ đụng tới mật khẩu / nội dung được đánh dấu bí mật
        let types = pb.types ?? []
        guard !types.contains(where: Self.concealedTypes.contains) else { return }

        // 4. Chỉ nhận chữ, bỏ chuỗi quá ngắn/quá dài, link, toàn số
        guard let raw = pb.string(forType: .string) else { return }
        let text = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        guard Self.isTranslatable(text) else { return }

        // 5. Trùng với lần vừa dịch trong 60 giây → bỏ qua
        if text == lastText, Date().timeIntervalSince(lastTextDate) < 60 { return }

        // 6. Ngôn ngữ phải khớp một cặp hội thoại đang có
        guard let convID = store.receiveClipboardText(text) else { return }
        lastText = text
        lastTextDate = Date()

        // Hiện khung dịch nhanh (không giành focus khỏi WeChat) nếu cửa sổ lớn không ở phía trước
        MenuBarController.shared.revealForIncoming(conversation: convID)
    }

    private static func isTranslatable(_ text: String) -> Bool {
        guard (2...5_000).contains(text.count) else { return false }
        // Toàn link
        if !text.contains(where: \.isWhitespace), let url = URL(string: text), url.scheme != nil { return false }
        // Không có chữ cái nào (chỉ số, ký hiệu, mã)
        guard text.unicodeScalars.contains(where: { CharacterSet.letters.contains($0) }) else { return false }
        return true
    }
}

/// Tên và icon của một app theo bundle ID (dùng trong Cài đặt và menu).
enum AppInfo {
    static func url(for bundleID: String) -> URL? {
        NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundleID)
    }

    static func name(for bundleID: String) -> String {
        guard let url = url(for: bundleID) else { return bundleID }
        return FileManager.default.displayName(atPath: url.path).replacingOccurrences(of: ".app", with: "")
    }

    static func icon(for bundleID: String) -> NSImage {
        guard let url = url(for: bundleID) else { return NSImage(systemSymbolName: "app", accessibilityDescription: nil) ?? NSImage() }
        return NSWorkspace.shared.icon(forFile: url.path)
    }
}
